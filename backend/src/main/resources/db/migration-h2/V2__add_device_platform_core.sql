CREATE TABLE IF NOT EXISTS organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_organizations_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_sites_organization_code UNIQUE (organization_id, code),
    CONSTRAINT fk_sites_organization FOREIGN KEY (organization_id) REFERENCES organizations (id)
);

CREATE TABLE IF NOT EXISTS spaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL,
    parent_id BIGINT,
    name VARCHAR(255) NOT NULL,
    path VARCHAR(512) NOT NULL,
    CONSTRAINT uk_spaces_site_path UNIQUE (site_id, path),
    CONSTRAINT fk_spaces_site FOREIGN KEY (site_id) REFERENCES sites (id),
    CONSTRAINT fk_spaces_parent FOREIGN KEY (parent_id) REFERENCES spaces (id)
);

