CREATE TABLE IF NOT EXISTS device_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    transport VARCHAR(50) NOT NULL,
    profile_id VARCHAR(100),
    external_id VARCHAR(255),
    status VARCHAR(50),
    metadata_json VARCHAR(4000),
    CONSTRAINT fk_device_connections_device FOREIGN KEY (device_id) REFERENCES devices (id)
);

CREATE INDEX IF NOT EXISTS idx_device_connections_device ON device_connections (device_id);

CREATE TABLE IF NOT EXISTS device_commands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command_id VARCHAR(100) NOT NULL,
    device_id BIGINT NOT NULL,
    type VARCHAR(100) NOT NULL,
    parameters_json VARCHAR(4000),
    idempotency_key VARCHAR(128),
    status VARCHAR(50),
    error_message VARCHAR(2000),
    requested_at TIMESTAMP,
    acknowledged_at TIMESTAMP,
    CONSTRAINT uk_device_commands_command_id UNIQUE (command_id),
    CONSTRAINT fk_device_commands_device FOREIGN KEY (device_id) REFERENCES devices (id)
);

CREATE INDEX IF NOT EXISTS idx_device_commands_device_requested_at ON device_commands (device_id, requested_at);
CREATE INDEX IF NOT EXISTS idx_device_commands_device_idempotency ON device_commands (device_id, idempotency_key);

CREATE TABLE IF NOT EXISTS activity_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    detail VARCHAR(2000),
    payload_json VARCHAR(4000),
    occurred_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_activity_events_device FOREIGN KEY (device_id) REFERENCES devices (id)
);

CREATE INDEX IF NOT EXISTS idx_activity_events_device_occurred_at ON activity_events (device_id, occurred_at);
