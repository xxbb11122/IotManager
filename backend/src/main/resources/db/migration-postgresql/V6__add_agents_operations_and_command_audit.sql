CREATE TABLE IF NOT EXISTS edge_agents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id VARCHAR(100) NOT NULL,
    site_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    version VARCHAR(100),
    status VARCHAR(30) NOT NULL,
    last_seen TIMESTAMP,
    metadata_json TEXT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_edge_agents_agent_id UNIQUE (agent_id),
    CONSTRAINT fk_edge_agents_site FOREIGN KEY (site_id) REFERENCES sites (id)
);

CREATE INDEX IF NOT EXISTS idx_edge_agents_site_status ON edge_agents (site_id, status);

CREATE TABLE IF NOT EXISTS discovered_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id VARCHAR(100) NOT NULL,
    agent_id BIGINT NOT NULL,
    external_id VARCHAR(255) NOT NULL,
    profile_id VARCHAR(100) NOT NULL,
    profile_version INTEGER NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    manufacturer VARCHAR(100),
    model VARCHAR(100),
    endpoint VARCHAR(500),
    status VARCHAR(30) NOT NULL,
    claimed_device_id BIGINT,
    first_seen TIMESTAMP NOT NULL,
    last_seen TIMESTAMP NOT NULL,
    metadata_json TEXT,
    CONSTRAINT uk_discovered_devices_candidate UNIQUE (candidate_id),
    CONSTRAINT uk_discovered_devices_agent_external UNIQUE (agent_id, external_id),
    CONSTRAINT fk_discovered_devices_agent FOREIGN KEY (agent_id) REFERENCES edge_agents (id),
    CONSTRAINT fk_discovered_devices_device FOREIGN KEY (claimed_device_id) REFERENCES devices (id)
);

CREATE INDEX IF NOT EXISTS idx_discovered_devices_status ON discovered_devices (agent_id, status);

CREATE TABLE IF NOT EXISTS device_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(100) NOT NULL,
    site_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(1000),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    archived_at TIMESTAMP,
    CONSTRAINT uk_device_groups_public_id UNIQUE (public_id),
    CONSTRAINT uk_device_groups_site_name UNIQUE (site_id, name),
    CONSTRAINT fk_device_groups_site FOREIGN KEY (site_id) REFERENCES sites (id)
);

CREATE TABLE IF NOT EXISTS device_group_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    device_id BIGINT NOT NULL,
    added_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_device_group_member UNIQUE (group_id, device_id),
    CONSTRAINT fk_device_group_members_group FOREIGN KEY (group_id) REFERENCES device_groups (id),
    CONSTRAINT fk_device_group_members_device FOREIGN KEY (device_id) REFERENCES devices (id)
);

CREATE INDEX IF NOT EXISTS idx_device_group_members_device ON device_group_members (device_id);

CREATE TABLE IF NOT EXISTS command_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id VARCHAR(100) NOT NULL,
    site_id BIGINT NOT NULL,
    group_id BIGINT,
    target_kind VARCHAR(30) NOT NULL,
    target_label VARCHAR(255) NOT NULL,
    type VARCHAR(100) NOT NULL,
    parameters_json TEXT,
    status VARCHAR(50) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    requested_via VARCHAR(100) NOT NULL,
    requested_by VARCHAR(100),
    requested_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    expires_at TIMESTAMP,
    retry_of_batch_id VARCHAR(100),
    total_count INTEGER NOT NULL DEFAULT 0,
    pending_count INTEGER NOT NULL DEFAULT 0,
    sent_count INTEGER NOT NULL DEFAULT 0,
    acknowledged_count INTEGER NOT NULL DEFAULT 0,
    failed_count INTEGER NOT NULL DEFAULT 0,
    rejected_count INTEGER NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_command_batches_batch_id UNIQUE (batch_id),
    CONSTRAINT uk_command_batches_site_idempotency UNIQUE (site_id, idempotency_key),
    CONSTRAINT fk_command_batches_site FOREIGN KEY (site_id) REFERENCES sites (id),
    CONSTRAINT fk_command_batches_group FOREIGN KEY (group_id) REFERENCES device_groups (id)
);

