UPDATE device_commands
SET request_origin = COALESCE(request_origin, 'LEGACY'),
    completed_at = CASE WHEN status IN ('ACKNOWLEDGED', 'FAILED') THEN COALESCE(acknowledged_at, requested_at) ELSE NULL END
WHERE request_origin IS NULL OR TRIM(request_origin) = '';

