    ON device_commands (batch_id, status);

CREATE TABLE IF NOT EXISTS command_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command_id BIGINT NOT NULL,
    from_status VARCHAR(50),
    to_status VARCHAR(50) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    detail VARCHAR(2000),
    payload_json TEXT,
    occurred_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_command_events_command FOREIGN KEY (command_id) REFERENCES device_commands (id)
);

CREATE INDEX IF NOT EXISTS idx_command_events_command_occurred
    ON command_events (command_id, occurred_at);

